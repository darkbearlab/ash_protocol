// The icon as an SVG string: one path of horizontal runs, pixel-crisp at `scale` screen pixels per map pixel.
export function iconSvg(name,scale=2){
 const map=MAPS[name];if(!map)return '';
 const h=map.length,w=map[0].length;let d='';
 map.forEach((row,y)=>{for(let x=0;x<w;){if(row[x]!=='#'){x++;continue;}let run=0;while(row[x+run]==='#')run++;d+=`M${x} ${y}h${run}v1h-${run}z`;x+=run;}});
 return `<svg class="px-icon" viewBox="0 0 ${w} ${h}" width="${w*scale}" height="${h*scale}" shape-rendering="crispEdges" aria-hidden="true" focusable="false"><path fill="currentColor" d="${d}"/></svg>`;
}

// Build step (wrangler.toml [build]): copies the game engine of every version in engines.json into
// .engines/<version>/<language>/src and writes src/engines.generated.js, which loads each copy lazily, so the Worker
// plays a run back with the exact rules and language it was played with. The game's text tables resolve when its
// modules load, so each language needs its own copy (src/index.js loads it with ASH_LANGUAGE set).
// A ref is a git tag or commit (git archive); 'WORKTREE' copies ../../src for local development.
import {readFileSync,writeFileSync,rmSync,mkdirSync,cpSync,existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';

const LANGUAGES=['zh-TW','en'];
const here=join(dirname(fileURLToPath(import.meta.url)),'..'),repo=join(here,'..','..'),out=join(here,'.engines');
const {versions}=JSON.parse(readFileSync(join(here,'engines.json'),'utf8'));
rmSync(out,{recursive:true,force:true});mkdirSync(out,{recursive:true});
const lines=[];
for(const [version,ref] of Object.entries(versions)){
 if(!/^\d+\.\d+\.\d+$/.test(version))throw new Error(`engines.json: bad version ${version}`);
 const first=join(out,version,LANGUAGES[0]);mkdirSync(first,{recursive:true});
 if(ref==='WORKTREE'){
  // CI may test against the worktree (ENGINES_ALLOW_WORKTREE=1), never deploy it.
  if(process.env.CI&&!process.env.ENGINES_ALLOW_WORKTREE)throw new Error(`engines.json: ${version} points at WORKTREE, which is for local development only`);
  cpSync(join(repo,'src'),join(first,'src'),{recursive:true});
 }else{
  const tar=join(out,`${version}.tar`);
  execFileSync('git',['-C',repo,'archive','--format=tar','-o',tar,ref,'src']);
  execFileSync('tar',[...(process.platform==='win32'?['--force-local']:[]),'-xf',tar,'-C',first]);rmSync(tar);
 }
 const shipped=readFileSync(join(first,'src','version.js'),'utf8').match(/VERSION='([^']+)'/)?.[1];
 if(shipped!==version)throw new Error(`engines.json: ${ref} is version ${shipped}, not ${version}`);
 if(!existsSync(join(first,'src','ranked-daily.js')))throw new Error(`engines.json: ${version} has no src/ranked-daily.js`);
 for(const lang of LANGUAGES.slice(1))cpSync(join(first,'src'),join(out,version,lang,'src'),{recursive:true});
 lines.push(` '${version}':{${LANGUAGES.map(l=>`'${l}':()=>import('../.engines/${version}/${l}/src/ranked-daily.js')`).join(',')}},`);
}
writeFileSync(join(here,'src','engines.generated.js'),`// Generated by scripts/engines.mjs from engines.json. Do not edit.\nexport const ENGINES={\n${lines.join('\n')}\n};\n`);
console.log(`engines: ${Object.keys(versions).join(', ')||'none'} × ${LANGUAGES.join(', ')}`);
